// ── PDF Receipt Generator ─────────────────────────────────────
function generateReturnReceiptPDF({ partyName, returnType, returnDate, sareeDetails, subTotal, gstRate, gstAmount, total, notes }) {
  const doc = new jsPDF({ unit: "pt", format: "a5" });
  const W = doc.internal.pageSize.getWidth();
  let y = 40;

  const line = (text, x, size = 10, style = "normal", color = [30, 30, 30]) => {
    doc.setFontSize(size);
    doc.setFont("helvetica", style);
    doc.setTextColor(...color);
    doc.text(text, x, y);
  };
  const hr = (col = [220, 220, 220]) => {
    doc.setDrawColor(...col);
    doc.line(30, y, W - 30, y);
    y += 10;
  };

  // Header
  line("RETURN RECEIPT", W / 2, 16, "bold", [30, 30, 30]);
  doc.setFontSize(16); // for getTextWidth
  const titleW = doc.getTextWidth("RETURN RECEIPT");
  doc.setDrawColor(234, 179, 8);
  doc.setLineWidth(1.5);
  doc.line(W / 2 - titleW / 2, y + 3, W / 2 + titleW / 2, y + 3);
  y += 24;

  line(returnType, W / 2, 10, "bold", [180, 140, 0]);
  doc.setFontSize(10);
  const rtW = doc.getTextWidth(returnType);
  doc.text(returnType, W / 2 - rtW / 2, y);
  y -= 10; // already drawn by line(), adjust
  y += 20;

  // Party & Date
  line(`Party: ${partyName}`, 30, 10, "bold");
  const dateStr = returnDate ? returnDate.split("-").reverse().join("/") : "";
  doc.setFontSize(10); doc.setFont("helvetica", "normal");
  doc.text(`Date: ${dateStr}`, W - 30, y, { align: "right" });
  y += 18;
  hr();

  // Items header
  line("Saree", 30, 9, "bold", [80, 80, 80]);
  doc.setFontSize(9); doc.setFont("helvetica", "bold"); doc.setTextColor(80, 80, 80);
  doc.text("Qty", W / 2 + 10, y);
  doc.text("Rate", W / 2 + 55, y);
  doc.text("Value", W - 30, y, { align: "right" });
  y += 16;

  // Items
  (sareeDetails || []).forEach((item) => {
    doc.setFontSize(9); doc.setFont("helvetica", "normal"); doc.setTextColor(30, 30, 30);
    const name = item.sareeName || "";
    doc.text(name.length > 28 ? name.slice(0, 26) + "…" : name, 30, y);
    doc.text(String(item.quantity), W / 2 + 10, y);
    doc.text(fmtINR(item.pricePerUnit), W / 2 + 55, y);
    doc.text(fmtINR(item.subtotal ?? item.quantity * item.pricePerUnit), W - 30, y, { align: "right" });
    y += 15;
  });

  y += 4;
  hr();

  // Totals
  const row = (label, value, bold = false, color = [30, 30, 30]) => {
    doc.setFontSize(9);
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setTextColor(...color);
    doc.text(label, W - 120, y);
    doc.text(value, W - 30, y, { align: "right" });
    y += 14;
  };

  row("Sub Total", fmtINR(subTotal));
  if (gstAmount > 0) row(`GST (${gstRate}%)`, `+ ${fmtINR(gstAmount)}`, false, [34, 139, 34]);
  row("Total Return", fmtINR(total), true, [180, 100, 0]);

  // Notes
  if (notes) {
    y += 8;
    hr([200, 200, 200]);
    line("Notes:", 30, 8, "bold", [120, 120, 120]);
    y += 12;
    doc.setFontSize(8); doc.setFont("helvetica", "normal"); doc.setTextColor(80, 80, 80);
    const wrapped = doc.splitTextToSize(notes, W - 60);
    doc.text(wrapped, 30, y);
    y += wrapped.length * 10;
  }

  // Footer
  y = doc.internal.pageSize.getHeight() - 20;
  doc.setFontSize(7); doc.setFont("helvetica", "normal"); doc.setTextColor(160, 160, 160);
  doc.text("Generated by SS-JT · Saree Stock & Journal Tracker", W / 2, y, { align: "center" });

  return doc;
}

