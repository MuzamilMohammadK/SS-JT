    const fileName = `Return_${savedData.partyName.replace(/\s+/g, "_")}_${savedData.returnDate}.pdf`;

    // Try Web Share API (works on Android/iOS)
    if (navigator.canShare) {
      try {
        const blob = pdf.output("blob");
        const file = new File([blob], fileName, { type: "application/pdf" });
        if (navigator.canShare({ files: [file] })) {
          await navigator.share({ files: [file], title: `${savedData.returnType} Receipt`, text: `Return receipt for ${savedData.partyName}` });
          return;
        }
      } catch (e) {
        // fall through
      }
    }

    // Desktop fallback: download PDF + open WhatsApp with text summary
