// ── TypeBadge ─────────────────────────────────────────────────
function TypeBadge({ type }) {
  if (type === "Sale"     || type === "Given")
    return <span className="badge-indigo"><ArrowUpRight className="w-3 h-3" />Sale</span>;
  if (type === "Purchase" || type === "Taken")
    return <span className="badge-rose"><ArrowDownLeft className="w-3 h-3" />Purchase</span>;
  if (type === "Sale Return")
    return <span className="badge-amber"><RotateCcw className="w-3 h-3" />Sale Return</span>;
  if (type === "Purchase Return")
    return <span className="badge-teal"><RotateCcw className="w-3 h-3" />Purchase Return</span>;
  return <span className="badge-slate">{type}</span>;
}

function StatusBadge({ status }) {
  return status === "Settled"
    ? <span className="badge-emerald"><CheckCircle2 className="w-3 h-3" />Settled</span>
    : <span className="badge-amber"><Clock className="w-3 h-3" />Pending</span>;
}

function formatDate(dateStr) {
  if (!dateStr) return "—";
  const [y, m, d] = dateStr.split("-");
  return `${d}/${m}/${y}`;
}

// ── Compute unified payment terms / installments ──────────────
function getPaymentTerms(tx) {
  const rawLogs = tx.paymentLogs || [];
  const logSum = rawLogs.reduce((sum, l) => sum + (Number(l.amount) || 0), 0);
  const totalPaid = Number(tx.amountPaid) || 0;
  const initialAmount = parseFloat(Math.max(0, totalPaid - logSum).toFixed(2));

  const terms = [];

  if (initialAmount > 0.005) {
    terms.push({
      termNumber: 1,
      title: "Term 1 · Initial Payment",
      date: tx.transactionDate,
      amount: initialAmount,
      type: (tx.type === "Purchase" || tx.type === "Taken") ? "Payment to Supplier" : "Receipt from Customer",
      isInitial: true,
      collectedBy: tx.lastCollectedBy || null,
    });
  }

  rawLogs.forEach((log) => {
    terms.push({
      termNumber: terms.length + 1,
      title: `Term ${terms.length + 1} · ${log.type || "Installment"}`,
      date: log.date ? log.date.slice(0, 10) : tx.transactionDate,
      rawDate: log.date,
      amount: Number(log.amount) || 0,
      type: log.type || "Settlement Payment",
      isInitial: false,
      collectedBy: log.collectedBy || log.collectedByOwner || null,
      note: log.note || null,
      // payment mode fields
      paymentMode: log.paymentMode || null,
      paymentDate: log.paymentDate || null,
      chequeNo: log.chequeNo || null,
      chequeReceivedDate: log.chequeReceivedDate || null,
      chequeDate: log.chequeDate || null,
      chequePassDate: log.chequePassDate || null,
      neftRefNo: log.neftRefNo || null,
    });
  });

  let cumulative = 0;
  const total = Number(tx.totalAmount) || 0;
  return terms.map((t) => {
    cumulative = parseFloat((cumulative + t.amount).toFixed(2));
    const balanceAfter = parseFloat(Math.max(0, total - cumulative).toFixed(2));
    return { ...t, cumulative, balanceAfter };
  });
}

// ── PDF Generator for Settled Transactions ──────────────────────
function generateSettledReceiptPDF(tx) {
  const doc = new jsPDF({ unit: "pt", format: "a5" });
  const W = doc.internal.pageSize.getWidth();
  let y = 35;

  const txt = (text, x, size = 10, style = "normal", color = [30, 30, 30], align = "left") => {
    doc.setFontSize(size); doc.setFont("helvetica", style); doc.setTextColor(...color);
    doc.text(String(text), x, y, { align });
  };
  const hr = (col = [220, 220, 220]) => {
    doc.setDrawColor(...col); doc.line(30, y, W - 30, y); y += 10;
  };
  const row = (label, value, bold = false, color = [30, 30, 30]) => {
    doc.setFontSize(9); doc.setFont("helvetica", bold ? "bold" : "normal"); doc.setTextColor(...color);
    doc.text(label, W - 140, y); doc.text(value, W - 30, y, { align: "right" }); y += 14;
  };

  // Header
  txt("PAYMENT SETTLEMENT RECEIPT", W / 2, 15, "bold", [30, 30, 30], "center"); y += 4;
  doc.setDrawColor(34, 197, 94); doc.setLineWidth(1.5);
  doc.setFontSize(15); const hw = doc.getTextWidth("PAYMENT SETTLEMENT RECEIPT");
  doc.line(W / 2 - hw / 2, y, W / 2 + hw / 2, y); y += 18;

  // Party & Date
  txt(`Party: ${tx.partyName || "—"}`, 30, 10, "bold");
  const dateStr = tx.transactionDate ? tx.transactionDate.split("-").reverse().join("/") : "";
  txt(`Date: ${dateStr}`, W - 30, 10, "normal", [80, 80, 80], "right"); y += 16;

  if (tx.invoiceNumber) {
    txt(`Invoice #${tx.invoiceNumber}`, 30, 9, "bold", [79, 70, 229]);
    txt(`Type: ${tx.type || "Sale"}`, W - 30, 9, "normal", [100, 100, 100], "right");
    y += 14;
  }
  hr();

  // Sarees / Items summary (if available)
  const items = tx.sareeDetails || [];
  if (items.length > 0) {
    txt("Items / Sarees", 30, 8.5, "bold", [100, 100, 100]);
    txt("Qty", W / 2 + 10, 8.5, "bold", [100, 100, 100]);
    txt("Rate", W / 2 + 55, 8.5, "bold", [100, 100, 100]);
    txt("Amount", W - 30, 8.5, "bold", [100, 100, 100], "right");
    y += 13;

    items.forEach((it) => {
      if (y > doc.internal.pageSize.getHeight() - 140) return;
      const name = it.sareeName || "Saree";
      txt(name.length > 26 ? name.slice(0, 24) + "…" : name, 30, 8.5, "normal", [40, 40, 40]);
      txt(String(it.quantity || 1), W / 2 + 10, 8.5, "normal", [40, 40, 40]);
      txt(fmtINR(it.pricePerUnit || 0), W / 2 + 55, 8.5, "normal", [40, 40, 40]);
      txt(fmtINR(it.subtotal ?? it.lineTotal ?? ((it.quantity || 1) * (it.pricePerUnit || 0))), W - 30, 8.5, "normal", [40, 40, 40], "right");
      y += 13;
    });
    hr();
  }

  // Payment Breakdown
  const total = Number(tx.totalAmount) || 0;
  const paid = Number(tx.amountPaid) || total;
  const discount = Number(tx.discount) || 0;
  const due = Number(tx.pendingDue) || 0;

  if (tx.subTotalAmount && tx.subTotalAmount !== tx.totalAmount) {
    row("Subtotal", fmtINR(tx.subTotalAmount));
  }
  if (tx.gstAmount > 0) {
    row(`GST (${tx.gstRate}%)`, `+ ${fmtINR(tx.gstAmount)}`, false, [34, 139, 34]);
  }
  row("Invoice Total", fmtINR(total), true);
  row("Amount Paid", fmtINR(paid), true, [34, 139, 34]);
  if (discount > 0) {
    row("Discount / Waiver", `- ${fmtINR(discount)}`, false, [217, 119, 6]);
  }
  row("Remaining Due", fmtINR(due), true, due <= 0.005 ? [34, 197, 94] : [220, 38, 38]);

  // Fully Settled badge
  y += 6;
  doc.setFillColor(34, 197, 94, 0.08); doc.setDrawColor(34, 197, 94);
  doc.roundedRect(30, y, W - 60, 22, 5, 5, "FD");
  txt("FULLY SETTLED ✓", W / 2, 9, "bold", [34, 197, 94], "center");
  y += 28;

  // Payment terms / installments history
  const terms = getPaymentTerms(tx);
  if (terms.length > 0 && y < doc.internal.pageSize.getHeight() - 75) {
    txt("Payment History / Terms:", 30, 8.5, "bold", [80, 80, 80]); y += 12;
    terms.forEach((t) => {
      if (y > doc.internal.pageSize.getHeight() - 40) return;
      const tDate = t.date ? t.date.split("-").reverse().join("/") : "";
      const extra = [
        t.paymentMode ? `${t.paymentMode}` : null,
        t.chequeNo ? `#${t.chequeNo}` : null,
        t.neftRefNo ? `Ref:${t.neftRefNo}` : null,
        t.collectedBy ? `By: ${t.collectedBy}` : null,
      ].filter(Boolean).join(" · ");
      txt(`${t.title || `Term ${t.termNumber}`} (${tDate}) ${extra ? `· ${extra}` : ""}`, 30, 7.5, "normal", [90, 90, 90]);
      txt(fmtINR(t.amount), W - 30, 7.5, "bold", [34, 139, 34], "right");
      y += 11;
    });
  }

  // Footer
  y = doc.internal.pageSize.getHeight() - 18;
  doc.setFontSize(7); doc.setFont("helvetica", "normal"); doc.setTextColor(160, 160, 160);
  doc.text("Generated by SS-JT · Saree Stock & Journal Tracker", W / 2, y, { align: "center" });

  return doc;
}

// ── Share Settled Transaction Handler ──────────────────────────
async function shareSettledTransaction(tx) {
  try {
    const doc = generateSettledReceiptPDF(tx);
    const safeParty = (tx.partyName || "Party").replace(/[^a-zA-Z0-9_-]/g, "_");
    const invStr = tx.invoiceNumber ? `INV_${tx.invoiceNumber}_` : "";
    const fileName = `Settled_Receipt_${safeParty}_${invStr}${new Date().toISOString().slice(0, 10)}.pdf`;

    if (navigator.canShare) {
      try {
        const blob = doc.output("blob");
        const file = new File([blob], fileName, { type: "application/pdf" });
        if (navigator.canShare({ files: [file] })) {
          await navigator.share({
            files: [file],
            title: `Settled Payment Receipt - ${tx.partyName}`,
            text: `Payment Receipt for ${tx.partyName}${tx.invoiceNumber ? ` (Invoice #${tx.invoiceNumber})` : ""} - Fully Settled ✅`,
          });
          toast.success("Settled receipt shared successfully!");
          return;
        }
      } catch (e) {
        if (e.name === "AbortError") return;
      }
    }

    doc.save(fileName);
    const dateStr = tx.transactionDate ? tx.transactionDate.split("-").reverse().join("/") : "";
    const lines = [
      `*PAYMENT SETTLEMENT RECEIPT*`,
      `Party: *${tx.partyName}*`,
      tx.invoiceNumber ? `Invoice #: *${tx.invoiceNumber}*` : null,
      `Date: ${dateStr}`,
      `Type: ${tx.type || "Sale"}`,
      `-----------------------------`,
      `Total Amount: *${fmtINR(tx.totalAmount)}*`,
      `Amount Paid: *${fmtINR(tx.amountPaid)}*`,
      Number(tx.discount) > 0 ? `Discount: -${fmtINR(tx.discount)}` : null,
      `Remaining Due: *${fmtINR(0)}*`,
      `Status: ✅ *FULLY SETTLED*`,
      tx.lastCollectedBy ? `Collected By: ${tx.lastCollectedBy}` : null,
      `-----------------------------`,
      `_Receipt PDF downloaded to your device._`,
    ].filter(Boolean).join("\n");

    window.open(`https://wa.me/?text=${encodeURIComponent(lines)}`, "_blank");
    toast.success("Receipt PDF downloaded & WhatsApp opened!");
  } catch (err) {
    console.error("Error sharing settled receipt:", err);
    toast.error("Failed to share settled receipt.");
  }
}

